"""Reproducible retrieval benchmark on ten fully synthetic documents.

The offline sparse baseline uses the real parser, chunker, SQLite FTS5/BM25,
selection path and retrieval metrics, WITHOUT indexing vectors in ChromaDB.

For the actual hybrid configuration, use --mode hybrid with a running Ollama
embeddinggemma server. No LLM answers are generated by this benchmark.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import math
import platform
import statistics
import sys
import tempfile
import time
from pathlib import Path

from localrag.config import Config
from localrag.engine import RAGEngine
from localrag.metrics import ndcg_at_k, recall_at_k, reciprocal_rank
from localrag.parsing import chunk_passages, parse_file, sha256_file, stable_id


ROOT = Path(__file__).resolve().parent
CORPUS = ROOT / "fixtures" / "corpus"
CASES = ROOT / "fixtures" / "questions.jsonl"


def percentile(values: list[float], fraction: float) -> float:
    """Report a stable nearest-rank percentile without extra dependencies."""
    ordered = sorted(values)
    return round(ordered[max(0, math.ceil(fraction * len(ordered)) - 1)], 3)


def load_cases() -> list[dict]:
    """Validate every gold label before starting the benchmark."""
    available = {path.name for path in CORPUS.glob("*.md")}
    cases = [json.loads(line) for line in CASES.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not cases or len(available) < 2:
        raise ValueError("Missing evaluation documents or questions")
    for case in cases:
        if not case.get("query") or not case.get("relevant_files"):
            raise ValueError(f"Missing query/relevance label: {case}")
        if not set(case["relevant_files"]) <= available:
            raise ValueError(f"Unknown gold document in: {case}")
    return cases


async def run_benchmark(mode: str, base_url: str, embedding_model: str) -> dict:
    cases = load_cases()
    with tempfile.TemporaryDirectory(prefix="localrag-synthetic-") as workspace:
        config = Config.model_validate({
            "app": {"data_dir": str(Path(workspace) / "data")},
            "embeddings": {"provider": "ollama", "base_url": base_url, "model": embedding_model},
            "retrieval": {"mode": mode, "final_top_k": 5, "dense_top_k": 20, "sparse_top_k": 20},
            "sources": [{"id": "synthetic", "type": "local", "path": str(CORPUS)}],
        })
        engine = RAGEngine(config)

        start = time.perf_counter()
        print("Indexing synthetic corpus...", file=sys.stderr, flush=True)
        if mode == "sparse":
            # Populate the same SQLite tables used in production without
            # pretending that embeddings were generated or tested.
            for path in sorted(CORPUS.glob("*.md")):
                doc_id = stable_id(f"synthetic:{path.name}")
                chunks = [{"id": stable_id(f"{doc_id}:{index}:{part.page}:{part.text}"),
                           "text": part.text, "page": part.page}
                          for index, part in enumerate(chunk_passages(
                              parse_file(path), config.retrieval.chunk_chars,
                              config.retrieval.chunk_overlap))]
                engine.storage.replace_document({
                    "id": doc_id, "source_id": "synthetic", "relative_path": path.name,
                    "title": path.name, "fingerprint": sha256_file(path),
                }, chunks)
            engine.save_signature()
            indexed_count = len(list(CORPUS.glob("*.md")))
        else:
            indexed = await asyncio.wait_for(engine.sync_source("synthetic"), timeout=600)
            if indexed["failed"]:
                raise RuntimeError(f"Incomplete synthetic ingestion: {indexed}")
            indexed_count = indexed["indexed"]
        print("Indexed successfully; evaluating queries...", file=sys.stderr, flush=True)
        ingestion_s = round(time.perf_counter() - start, 3)
        if indexed_count != len(list(CORPUS.glob("*.md"))):
            raise RuntimeError(f"Expected {len(list(CORPUS.glob('*.md')))} docs; indexed {indexed_count}")

        # Keep warm-up separate from the measured questions.
        for case in cases[:2]:
            await engine.retrieve(case["query"], ["synthetic"])

        scores = {"recall_at_1": [], "recall_at_5": [], "mrr_at_5": [], "ndcg_at_5": []}
        latency_ms = []
        misses = []
        per_category: dict[str, list[float]] = {}
        for case in cases:
            start = time.perf_counter()
            retrieved = await engine.retrieve(case["query"], ["synthetic"])
            latency_ms.append((time.perf_counter() - start) * 1000)
            found = list(dict.fromkeys(row["doc_id"] for row in retrieved))
            relevant = {stable_id(f"synthetic:{name}") for name in case["relevant_files"]}
            recall = recall_at_k(found, relevant, 5)
            scores["recall_at_1"].append(recall_at_k(found, relevant, 1))
            scores["recall_at_5"].append(recall)
            scores["mrr_at_5"].append(reciprocal_rank(found, relevant, 5))
            scores["ndcg_at_5"].append(ndcg_at_k(found, relevant, 5))
            per_category.setdefault(case.get("category", "other"), []).append(recall)
            if recall < 1:
                misses.append({"query": case["query"], "expected": case["relevant_files"]})

    return {
        "benchmark": "synthetic-retrieval-v1",
        "scope": "retrieval only; no generated answers, citations or LLM latency measured",
        "mode": mode,
        "embedding_model": embedding_model if mode == "hybrid" else "not used (sparse-only)",
        "indexing_scope": "parser + SQLite FTS5 only" if mode == "sparse" else "full Ollama/Chroma indexing",
        "platform": f"{platform.system()} {platform.machine()}",
        "python": platform.python_version(),
        "docs": len(list(CORPUS.glob("*.md"))),
        "questions": len(cases),
        "indexing_seconds": ingestion_s,
        "metrics": {key: round(statistics.mean(values), 4) for key, values in scores.items()},
        "recall_by_category": {key: round(statistics.mean(values), 4)
                               for key, values in sorted(per_category.items())},
        "query_latency_ms": {"p50": percentile(latency_ms, 0.5),
                             "p95": percentile(latency_ms, 0.95)},
        "misses": misses,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("sparse", "hybrid"), default="sparse")
    parser.add_argument("--ollama-base-url", default="http://127.0.0.1:11434")
    parser.add_argument("--embedding-model", default="embeddinggemma")
    parser.add_argument("--output", type=Path, help="Save the complete measured JSON report")
    args = parser.parse_args()

    result = asyncio.run(run_benchmark(args.mode, args.ollama_base_url, args.embedding_model))
    printed = json.dumps(result, indent=2, ensure_ascii=False) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(printed, encoding="utf-8")
    print(printed, end="")


if __name__ == "__main__":
    main()
